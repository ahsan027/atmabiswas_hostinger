            <div class="ge-why-body">
                <p>Climate change is already reshaping rural livelihoods across Bangladesh, and climate action increasingly depends on choices made at the household level, not only on national policy. Reducing carbon emissions at the household level — even through small changes like more efficient cooking — is a meaningful part of the wider climate response, especially when adopted by many families across many communities.</p>
                <p>Clean cooking solutions like Bondhu Chula matter for more than the environment. Traditional open-fire cooking exposes women and children to harmful indoor smoke on a daily basis, contributing to respiratory illness. A more efficient stove reduces this exposure, uses less fuel, and gives families back time and money that would otherwise go toward gathering firewood.</p>
                <p>Renewable energy, particularly solar power, addresses a different but equally urgent problem: energy access. Many rural households and small enterprises in Bangladesh operate without reliable electricity, limiting everything from evening study time to small business hours. Solar solutions like Souro Shokti offer a path to dependable power without extending a carbon-intensive grid into every village.</p>
                <p>Taken together, clean cooking and renewable energy form a practical foundation for sustainable development (টেকসই উন্নয়ন) and environmental sustainability — one that protects health, reduces environmental impact, supports rural development, and expands what rural families and communities are able to achieve.</p>
